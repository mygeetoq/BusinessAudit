def excerpt(path, max_lines=8):
    lines = (REPO / path).read_text(encoding="utf-8").splitlines()
    chosen = [(i+1, s.strip()) for i,s in enumerate(lines) if ("func " in s or "export default function" in s or "CREATE TABLE" in s or "ALTER TABLE" in s or "func Test" in s)]
    if not chosen: chosen = [(i+1,s.strip()) for i,s in enumerate(lines) if s.strip() and not s.lstrip().startswith(("//","--","import "))]
    return "; ".join(f"стр. {i}: {s[:95]}" for i,s in chosen[:max_lines])


