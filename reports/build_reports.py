def style(doc: Document) -> None:
    sec = doc.sections[0]
    sec.top_margin = Cm(1.4)
    sec.bottom_margin = Cm(1.4)
    sec.left_margin = Cm(1.8)
    sec.right_margin = Cm(1.5)
    normal = doc.styles["Normal"]
    normal.font.name = "Arial"
    normal.font.size = Pt(9.5)
    normal.paragraph_format.space_after = Pt(3)
    for name, size in [("Title", 17.5), ("Heading 1", 12.5), ("Heading 2", 10.5)]:
        s = doc.styles[name]
        s.font.name = "Arial"
        s.font.size = Pt(size)
        s.font.bold = True


def intro(kind: str, number: int, topic: str, who: str = "Команда проекта") -> Document:
    d = Document()
    style(d)
    for line in ["Дисциплина «Управление программными проектами»", f"{kind} №{number}"]:
        p = d.add_paragraph(line)
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p = d.add_paragraph(topic, style="Title")
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    p = d.add_paragraph(TITLE)
    p.alignment = WD_ALIGN_PARAGRAPH.CENTER
    d.add_paragraph(f"Исполнитель: {who}")
    d.add_paragraph("ФИО / группа / вуз: заполняются командой перед сдачей")
    d.add_paragraph("Плановый период проекта: 1–30 сентября 2026 года. Подготовлено: 7 октября 2026 года.")
    d.add_paragraph("Сроки ниже — учебный план; текущие файлы не подтверждают исторические даты или личное авторство.")
    return d


def h(d, text): d.add_heading(text, 1)
def sub(d, text): d.add_heading(text, 2)
def p(d, text): d.add_paragraph(text)


def bullets(d, items):
    for item in items:
        d.add_paragraph(item, style="List Bullet")


def table(d, headers, rows):
    t = d.add_table(rows=1, cols=len(headers))
    t.style = "Table Grid"
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for c, val in zip(t.rows[0].cells, headers): c.text = str(val)
    header_props = t.rows[0]._tr.get_or_add_trPr()
    repeat = OxmlElement("w:tblHeader")
    repeat.set(qn("w:val"), "true")
    header_props.append(repeat)
    for row in rows:
        cells = t.add_row().cells
        for c, val in zip(cells, row): c.text = str(val)
    for row in t.rows:
        for c in row.cells:
            for para in c.paragraphs:
                for run in para.runs: run.font.size = Pt(7.5)
    return t


